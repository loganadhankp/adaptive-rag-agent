from typing import Literal

# flake8: noqa - prompt templates intentionally contain long lines
from langchain_core.prompts import ChatPromptTemplate
from pydantic import BaseModel, Field


class HallucinationResult(BaseModel):
    """Result of hallucination check."""

    verdict: Literal["supported", "unsupported"] = Field(
        description="Whether the answer is supported by the source documents"
    )
    reasoning: str = Field(description="Explanation of the verdict")
    unsupported_claims: list[str] = Field(
        default_factory=list,
        description="List of specific claims not supported by sources",
    )


# ──────────────────────────────────────────────────────────────────────────────
# MODE 1: Strict Factual Hallucination Check
# ──────────────────────────────────────────────────────────────────────────────

FACTUAL_HALLUCINATION_SYSTEM_PROMPT = """You are a strict hallucination detector.
Your task is to compare a generated answer against a set of source documents to determine if the answer is completely supported by the evidence.

Guidelines:
- Analyze every claim made in the generated answer.
- Check if the claim can be directly inferred or found in the source documents.
- If ANY claim in the answer is not supported by the source documents, mark the verdict as 'unsupported' and list the unsupported claims.
- If ALL claims are supported, mark the verdict as 'supported'.
- Do not evaluate the quality of the writing, only its factual grounding in the provided documents."""

# ──────────────────────────────────────────────────────────────────────────────
# MODE 2: Analytical Hallucination Check (for analysis/recommendation/comparison/summarization)
# ──────────────────────────────────────────────────────────────────────────────

ANALYTICAL_HALLUCINATION_SYSTEM_PROMPT = """You are a hallucination detector for analytical and advisory responses.
The generated answer contains a mix of: (a) factual references to source document content, and (b) the LLM's own analytical reasoning, recommendations, or assessments applied to that content.

Guidelines:
- Check that any **factual claim about what the documents contain** is accurate. For example, if the answer says "The resume lists Python as a skill", verify that the source documents do mention Python.
- **Analytical opinions, recommendations, assessments, and suggestions** generated by the LLM are ALLOWED and should NOT be flagged as hallucinations. For example, "The resume could benefit from adding more quantified metrics" is a valid recommendation, not a hallucination.
- Only mark the verdict as 'unsupported' if the answer **misrepresents or fabricates facts about the source documents** (e.g., claims the resume mentions a degree that it doesn't).
- If all factual references to documents are accurate (even if the answer includes LLM reasoning beyond what's written), mark the verdict as 'supported'.
- Do not penalize the answer for providing analytical value beyond literal document content."""

HALLUCINATION_HUMAN_PROMPT = """Source Documents:
{documents}

Generated Answer: {answer}"""

# Default (backward compatible)
HALLUCINATION_SYSTEM_PROMPT = FACTUAL_HALLUCINATION_SYSTEM_PROMPT

HALLUCINATION_PROMPT = ChatPromptTemplate.from_messages(
    [("system", HALLUCINATION_SYSTEM_PROMPT), ("human", HALLUCINATION_HUMAN_PROMPT)]
)

FACTUAL_HALLUCINATION_PROMPT = ChatPromptTemplate.from_messages(
    [("system", FACTUAL_HALLUCINATION_SYSTEM_PROMPT), ("human", HALLUCINATION_HUMAN_PROMPT)]
)

ANALYTICAL_HALLUCINATION_PROMPT = ChatPromptTemplate.from_messages(
    [("system", ANALYTICAL_HALLUCINATION_SYSTEM_PROMPT), ("human", HALLUCINATION_HUMAN_PROMPT)]
)

